import React from 'react';
import { test, expect, beforeEach, afterEach, vi } from 'vitest';
import { webcrypto } from 'node:crypto';
import { render, screen, fireEvent, cleanup, within, waitFor } from '@testing-library/react';
import MoneyTestApp from '../../src/homologacao/MoneyTestApp.jsx';
import { MONEY_TEST_KEY } from '../../src/homologacao/moneyTestStore.js';
Object.defineProperty(globalThis.crypto,'subtle',{value:webcrypto.subtle,configurable:true});
beforeEach(()=>{
  localStorage.clear();
  Object.defineProperty(navigator,'locks',{value:{request:async(key,task)=>task()},configurable:true});
});
afterEach(()=>cleanup());
const saved=()=>JSON.parse(localStorage.getItem(MONEY_TEST_KEY));
const moneySelect=()=>screen.getByRole('combobox',{name:'Moeda de exibição'});
test('cadastro real de Produtos salva 39990 PYG, reabre, preserva legado e não reinterpreta ao mudar padrão',async()=>{
  render(<MoneyTestApp/>);
  fireEvent.click(screen.getByRole('button',{name:'+ Novo Produto'}));
  expect(screen.getByRole('combobox',{name:'Moeda do preço'}).value).toBe('PYG');
  fireEvent.change(screen.getByRole('textbox',{name:'Nome do Item'}),{target:{value:'PRODUTO CRIADO NO TESTE'}});
  fireEvent.change(screen.getByRole('textbox',{name:'Custo do produto'}),{target:{value:'20.000'}});
  fireEvent.change(screen.getByRole('textbox',{name:'Preço de venda do produto'}),{target:{value:'39.990'}});
  fireEvent.change(screen.getByRole('spinbutton',{name:'Estoque vitrine'}),{target:{value:'10'}});
  fireEvent.click(screen.getByRole('button',{name:'Salvar Produto no Sistema'}));
  await waitFor(()=>expect(saved().produtos).toHaveLength(3));
  const product=saved().produtos.find(p=>p.nome==='PRODUTO CRIADO NO TESTE');
  expect(product.moneyPrices.values.sale).toMatchObject({amount:'39990',currency:'PYG'});
  expect(product.moneyPrices.values.cost).toMatchObject({amount:'20000',currency:'PYG'});
  const row=screen.getByText('PRODUTO CRIADO NO TESTE').closest('tr');
  expect(within(row).getByText('PYG 39.990')).toBeTruthy();
  fireEvent.change(moneySelect(),{target:{value:'BRL'}});
  fireEvent.click(screen.getByRole('button',{name:'Salvar padrão'}));
  await waitFor(()=>expect(saved().moedaPadrao).toBe('BRL'));
  expect(saved().produtos.find(p=>p.id===product.id).moneyPrices.values.sale.amount).toBe('39990');
  fireEvent.click(within(row).getByRole('button',{name:'Editar'}));
  expect(screen.getByRole('textbox',{name:'Preço de venda do produto'}).value).toBe('39990');
  expect(screen.getByRole('combobox',{name:'Moeda do preço'}).value).toBe('PYG');
  fireEvent.click(screen.getByRole('button',{name:'Salvar Produto no Sistema'}));
  await waitFor(()=>expect(saved().produtos.find(p=>p.id===product.id).moneyPrices.revision).toBe(2));
  expect(saved().produtos.find(p=>p.id==='fixture-ambiguous').precoBRL).toBe(39990);
});
test('PDV existente vende fixture PYG com snapshot, baixa estoque e comprovante imutável',async()=>{
  render(<MoneyTestApp/>);
  fireEvent.click(screen.getByRole('button',{name:/PDV Balcão/}));
  fireEvent(window,new CustomEvent('zenos:adicionar-item-pdv',{detail:saved().produtos[0]}));
  expect(await screen.findByText('MASSA — TESTE 39.990')).toBeTruthy();
  fireEvent.keyDown(window,{key:'F10'});
  const select=screen.getAllByRole('combobox').find(s=>[...s.options].some(o=>o.value==='dinheiro_pyg'));
  expect(select).toBeTruthy();
  fireEvent.change(select,{target:{value:'dinheiro_pyg'}});
  fireEvent.change(screen.getByPlaceholderText('0.00'),{target:{value:'39990'}});
  fireEvent.click(screen.getByRole('button',{name:'+ Lançar Pagamento'}));
  fireEvent.click(screen.getByRole('button',{name:'Liquidar no Caixa'}));
  fireEvent.click(await screen.findByRole('button',{name:'Continuar venda'}));
  await waitFor(()=>expect(saved().historicoVendas).toHaveLength(1));
  const sale=saved().historicoVendas[0];
  expect(sale.moneySnapshot.total).toMatchObject({amount:'39990',currency:'PYG'});
  expect(sale.moneySettlement.payments[0].amount).toMatchObject({amount:'39990',currency:'PYG'});
  expect(saved().produtos.find(p=>p.id==='fixture-massa-39990').estoque).toBe(19);
  expect(saved().produtos.find(p=>p.id==='fixture-ambiguous').precoBRL).toBe(39990);
  const snapshot=JSON.stringify(sale);
  fireEvent.click(screen.getByRole('button',{name:'Novo Atendimento'}));
  fireEvent.click(screen.getByRole('button',{name:'⚙'}));
  fireEvent.change(screen.getByRole('spinbutton',{name:'Cotação PYG'}),{target:{value:'460'}});
  fireEvent.click(screen.getByRole('button',{name:'Salvar câmbio de teste'}));
  await waitFor(()=>expect(saved().rates.PYG).toBe(460));
  expect(JSON.stringify(saved().historicoVendas[0])).toBe(snapshot);
  expect(saved().produtos[0].moneyPrices.values.sale.amount).toBe('39990');
});

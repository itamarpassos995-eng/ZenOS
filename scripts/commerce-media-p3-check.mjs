import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {prepararMidiaCommerce,dimensoesWebP,caminhoCommerceValido,derivarMiniaturaPath,produtoPertenceLoja} from '../functions/src/commerceMediaServiceCore.js';
import {validarRascunhoCommerce} from '../functions/src/commerceStudioCore.js';
let n=0;
const yes=(x)=>{assert.ok(x);n++},eq=(a,b)=>{assert.deepEqual(a,b);n++;},deny=(f,pat)=>{assert.throws(f,pat);n++;};
function fakeWebP(w=500,h=400){
 const b=Buffer.alloc(30);b.write('RIFF',0,'ascii');b.writeUInt32LE(22,4);b.write('WEBP',8,'ascii');b.write('VP8X',12,'ascii');b.writeUInt32LE(10,16);
 b.writeUIntLE(w-1,24,3);b.writeUIntLE(h-1,27,3);return b;
}
const full=fakeWebP(1200,900), thumb=fakeWebP(480,360);
eq(dimensoesWebP(full),{largura:1200,altura:900});
const payload={lojaId:'loja-A',produtoId:'A100',principalBase64:full.toString('base64'),miniaturaBase64:thumb.toString('base64')};
const planned=prepararMidiaCommerce(payload);
yes(planned.path.startsWith('commerce/loja-A/produtos/A100/galeria/'));
yes(planned.thumbPath.startsWith('commerce/loja-A/produtos/A100/miniaturas/'));
yes(planned.id.startsWith('img-'));
eq(prepararMidiaCommerce(payload).path,planned.path);
eq(caminhoCommerceValido(planned.path,'loja-A','A100'),true);
eq(caminhoCommerceValido(planned.path,'loja-B','A100'),false);
eq(caminhoCommerceValido(planned.path,'loja-A','A101'),false);
eq(derivarMiniaturaPath(planned.path,'loja-A','A100'),planned.thumbPath);
deny(()=>derivarMiniaturaPath(planned.path,'loja-B','A100'),/domínio/);
deny(()=>prepararMidiaCommerce({...payload,lojaId:'../outro'}),/Identidade/);
deny(()=>prepararMidiaCommerce({...payload,produtoId:'__proto__'}),/Identidade/);
deny(()=>prepararMidiaCommerce({...payload,principalBase64:'abcd!'}),/codificada/);
deny(()=>prepararMidiaCommerce({...payload,miniaturaBase64:Buffer.alloc(100).toString('base64')}),/WebP/);
deny(()=>prepararMidiaCommerce({...payload,principalBase64:fakeWebP(1900,200).toString('base64')}),/Dimensões/);
deny(()=>prepararMidiaCommerce({...payload,miniaturaBase64:fakeWebP(481,360).toString('base64')}),/Miniatura/);
deny(()=>prepararMidiaCommerce({...payload,principalBase64:Buffer.alloc(3_000_001).toString('base64')}),/inválidos/);
const cadastro=prepararMidiaCommerce({...payload,origem:'cadastro'});
yes(caminhoCommerceValido(cadastro.path,'loja-A','A100',{origem:'cadastro'}));
eq(caminhoCommerceValido(cadastro.path,'loja-A','A100',{origem:'galeria'}),false);
eq(produtoPertenceLoja({produtos:[{id:'A100'}]},'A100'),true);
eq(produtoPertenceLoja({produtos:[{id:'A100'},{id:'A100'}]},'A100'),false);
eq(produtoPertenceLoja({produtos:[{id:'A200'}]},'A100'),false);
eq(produtoPertenceLoja({},'A100'),false);
const media={id:'imgA',storagePath:planned.path,alt:'Nova',ordem:0};
const valid=validarRascunhoCommerce({aparencia:{},regras:{A100:{publicado:true,galeriaImagens:[media],fotoCadastroStoragePath:cadastro.path}}},'loja-A');
eq(valid.regras.A100.galeriaImagens.length,1);
eq(valid.regras.A100.galeriaImagens[0].url,'');
eq(valid.regras.A100.fotoCadastroStoragePath,cadastro.path);
deny(()=>validarRascunhoCommerce({regras:{A100:{galeriaImagens:[media]}}},'loja-B'),/não pertence/);
deny(()=>validarRascunhoCommerce({regras:{A100:{fotoCadastroStoragePath:cadastro.path}}},'loja-B'),/outra loja/);
deny(()=>validarRascunhoCommerce({regras:{A100:{galeriaImagens:Array.from({length:9},()=>media)}}},'loja-A'),/Limite/);
const studio=readFileSync(new URL('../src/components/ZenCommerceStudio.jsx',import.meta.url),'utf8');
const portal=readFileSync(new URL('../src/components/ZenCommercePortal.jsx',import.meta.url),'utf8');
const service=readFileSync(new URL('../functions/src/commerceMedia.js',import.meta.url),'utf8');
const api=readFileSync(new URL('../functions/src/commerceStudio.js',import.meta.url),'utf8');
yes(studio.includes('onUploadProductImage'));
yes(portal.includes("origem:'cadastro'"));
yes(portal.includes('prepararFotoProduto(blob)'));
yes(service.includes("protegerAmbienteMidiaCommerce"));
yes(service.includes('produtoPertenceLoja'));
yes(api.includes('validarReferenciasNoStorage'));
yes(api.includes('hidratarUrlsPrivadas'));
console.log(`Commerce Midia P3: ${n} verificações de upload, isolamento, migracao legada, preview privado e contratos.`);

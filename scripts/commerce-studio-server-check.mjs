import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as core from '../functions/src/commerceStudioCore.js';
import {aparenciaPadrao} from '../src/core/commerceAppearance.js';
const a=core.validarRascunhoCommerce({aparencia:aparenciaPadrao,regras:{produtoA:{publicado:true,precoOnlineBRL:12.34,fonteEstoque:'deposito',reservaMinima:3}}});
assert.equal(a.aparencia.banners.length,2);assert.equal(a.regras.produtoA.precoOnlineBRL,12.34);
assert.equal(a.regras.produtoA.reservaMinima,3);
assert.equal(a.regras.produtoA.fonteEstoque,'deposito');
assert.ok(!('saldoFiado' in a.regras.produtoA));
assert.deepEqual(Object.keys(a.aparencia).includes('adminSecret'),false);
assert.throws(()=>core.validarRascunhoCommerce({aparencia:{banners:Array.from({length:6},(_,i)=>({id:'b-'+i}))}}),/Máximo/);
assert.throws(()=>core.validarRascunhoCommerce({aparencia:{},regras:JSON.parse('{"__proto__":{"publicado":true}}')}),/ID/);
assert.throws(()=>core.validarRascunhoCommerce({aparencia:{},regras:{x:{reservaMinima:-1}}}),/inteiro/);
assert.throws(()=>core.validarRascunhoCommerce({aparencia:{},regras:{x:{precoOnlineBRL:NaN}}}),/Preço/);
const sanit=core.validarRascunhoCommerce({aparencia:{nomeLoja:'Nome\nInvalido',corPrincipal:'red',banners:[{id:'b-1',imagemDesktop:'javascript:alert(1)',caminho:'https://evil.test'}]}});
assert.equal(sanit.aparencia.corPrincipal,'#193D4E');
assert.equal(sanit.aparencia.banners[0].imagemDesktop,'');
assert.equal(sanit.aparencia.banners[0].caminho,'/catalogo');
assert.equal(sanit.aparencia.nomeLoja,'Nome Invalido');
assert.equal(core.validarRevisao(0,0),true);assert.equal(core.validarRevisao(0,1),false);
assert.throws(()=>core.validarRevisao(-1,0),/Revisão/);
assert.equal(core.resumoLicencaCommerce({status:'ativo',ativacaoConfirmadaServidor:true}).ativo,true);
assert.equal(core.resumoLicencaCommerce({status:'ativo',ativacaoConfirmadaServidor:false}).ativo,false);
assert.equal(core.resumoLicencaCommerce({status:'suspenso',ativacaoConfirmadaServidor:true}).ativo,false);
let lead=core.construirInteresseCommerce(null,'UID-EXAMPLE','BR','2026-10-15T00:00:00Z');
assert.equal(lead.documento.semCobranca,true);assert.equal(lead.documento.semAtivacao,true);
assert.equal(core.construirInteresseCommerce(lead.documento,'UID-EXAMPLE','BR','2026-10-15T00:00:00Z').jaSolicitado,true);
const fn=readFileSync(new URL('../functions/src/commerceStudio.js',import.meta.url),'utf8');
assert.match(fn,/if\(request\.data\?\.lojaId!==undefined\)/);
assert.match(fn,/request\.auth\?\.uid/);
assert.match(fn,/lojas\/\$\{lojaId\}\/commerce_private\/rascunho/);
assert.ok(!fn.includes("action==='ativar'"));
assert.ok(!fn.includes("action==='publicar'"));
console.log('Commerce P1: validação server-side, multi-tenant, rascunhos e solicitação comercial aprovados.');

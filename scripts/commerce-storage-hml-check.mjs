import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {protegerAmbienteMidiaCommerce,ambienteMidiaCommercePronto} from '../functions/src/commerceStorageSafetyCore.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
let count=0;
const ok=v=>{assert.ok(v);count++};
const eq=(a,b)=>{assert.deepEqual(a,b);count++};
const no=(value,expected)=>{assert.throws(()=>protegerAmbienteMidiaCommerce(value),expected);count++};
const demo={mediaEnabled:'true',homologacao:'true',projectId:'demo-zenos-local',bucket:'demo-zenos-local.appspot.com',storageEmulatorHost:'127.0.0.1:9199'};
const staging={mediaEnabled:'true',homologacao:'true',projectId:'zenos-staging-2026',bucket:'zenos-commerce-hml-zenos-staging-2026'};
eq(protegerAmbienteMidiaCommerce(demo),{bucket:demo.bucket,modo:'emulador'});
eq(protegerAmbienteMidiaCommerce(staging),{bucket:staging.bucket,modo:'nuvem-homologacao'});
no({...demo,mediaEnabled:'false'},/DESATIVADO/);
no({...demo,mediaEnabled:undefined},/DESATIVADO/);
no({...demo,homologacao:'false'},/DESATIVADO/);
no({...demo,homologacao:undefined},/DESATIVADO/);
no({...demo,projectId:undefined},/PROJETO_NAO_IDENTIFICADO/);
no({...demo,projectId:'zenos-ac6b2'},/PRODUCAO_BLOQUEADA/);
no({...staging,projectId:'zenos-ac6b2'},/PRODUCAO_BLOQUEADA/);
no({...demo,bucket:'zenos-ac6b2.firebasestorage.app'},/BUCKET_NAO_AUTORIZADO/);
no({...staging,bucket:'zenos-ac6b2.appspot.com'},/BUCKET_NAO_AUTORIZADO/);
no({...staging,bucket:'zenos-commerce-staging'},/BUCKET_DEVE_SER_EXCLUSIVO/);
no({...demo,bucket:'demo-other.appspot.com'},/EMULADOR_LOCAL_OBRIGATORIO/);
no({...demo,storageEmulatorHost:''},/EMULADOR_LOCAL_OBRIGATORIO/);
no({...demo,storageEmulatorHost:'10.0.1.2:9199'},/EMULADOR_LOCAL_OBRIGATORIO/);
no({...demo,storageEmulatorHost:'storage.googleapis.com:9199'},/EMULADOR_LOCAL_OBRIGATORIO/);
no({...staging,storageEmulatorHost:'127.0.0.1:9199'},/EMULADOR_NAO_PERMITIDO/);
no({...staging,bucket:'invalid_name?'},/BUCKET_NAO_AUTORIZADO/);
ok(!ambienteMidiaCommercePronto({}));
ok(!ambienteMidiaCommercePronto({GCLOUD_PROJECT:'zenos-ac6b2',ZENOS_COMMERCE_HOMOLOGACAO:'true',ZENOS_COMMERCE_MEDIA_ENABLED:'true',ZENOS_COMMERCE_STORAGE_BUCKET:'zenos-commerce-hml-zenos-ac6b2'}));
ok(ambienteMidiaCommercePronto({GCLOUD_PROJECT:'demo-zenos-local',ZENOS_COMMERCE_HOMOLOGACAO:'true',ZENOS_COMMERCE_MEDIA_ENABLED:'true',ZENOS_COMMERCE_STORAGE_BUCKET:demo.bucket,FIREBASE_STORAGE_EMULATOR_HOST:'localhost:9199'}));
const conf=JSON.parse(readFileSync(resolve(root,'firebase.commerce.homologacao.json'),'utf8'));
eq(conf.storage.rules,'storage.commerce.homologacao.rules');
eq(conf.emulators.storage.host,'127.0.0.1');
eq(conf.emulators.storage.port,9199);
eq(conf.emulators.auth.host,'127.0.0.1');
eq(conf.emulators.firestore.host,'127.0.0.1');
eq(conf.emulators.functions.host,'127.0.0.1');
const rules=readFileSync(resolve(root,'storage.commerce.homologacao.rules'),'utf8');
ok(/allow read, write: if false;/.test(rules));
ok(!/allow (read|write|create|update|delete): if (request\.auth != null|true)/.test(rules));
const service=readFileSync(resolve(root,'functions/src/commerceMedia.js'),'utf8');
ok(service.includes('protegerAmbienteMidiaCommerce'));
ok(!/getStorage\(app\)\.bucket\(\)/.test(service));
const api=readFileSync(resolve(root,'functions/src/commerceStudio.js'),'utf8');
ok(api.includes('ambienteMidiaCommercePronto(process.env)'));
console.log(`Commerce Storage HML: ${count} verificações aprovadas; produção bloqueada por padrão.`);
